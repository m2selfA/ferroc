//! Local fleet configuration ONLY. No network, relay activation or MCP tools.
use super::identity::{
    EndpointSlot, Fingerprint, IdentityStore, PeerAdmission, PeerApproval, Protection,
};
use anyhow::{Context, Result, ensure};
use clap::{Args, Subcommand, ValueEnum};
use serde_json::{Value, json};
use std::path::PathBuf;
use uuid::Uuid;
use zeroize::Zeroizing;

#[derive(Args)]
pub struct FleetArgs {
    /// Explicit trusted private identity directory (init creates it, not parents).
    #[arg(long)]
    store: PathBuf,
    #[arg(long)]
    fleet_id: Uuid,
    /// Existing agent device ID; never inferred or generated by this command.
    #[arg(long)]
    device_id: String,
    /// NAME of an environment variable containing an external 32-byte hex key.
    /// No key value in argv. Without this Windows uses CurrentUser DPAPI;
    /// other platforms refuse rather than falling back to plaintext.
    #[arg(long)]
    wrapping_key_env: Option<String>,
    #[command(subcommand)]
    action: FleetAction,
}
#[derive(Subcommand)]
enum FleetAction {
    /// Create one encrypted local identity; never overwrite or regenerate.
    Init,
    /// Show PUBLIC identity material and fingerprint for independent approval.
    Identity,
    /// Explicit peer approval and roster operations (no discovery or TOFU).
    Peer {
        #[command(subcommand)]
        action: PeerAction,
    },
    /// Bind URLs to an ALREADY approved key (no DNS or connection attempt).
    Endpoint {
        #[command(subcommand)]
        action: EndpointAction,
    },
}
#[derive(Subcommand)]
enum PeerAction {
    Enroll {
        #[arg(long)]
        peer_device: String,
        #[arg(long)]
        label: String,
        #[arg(long)]
        public_key: String,
        /// Obtain through an independently verified channel; never auto-accepted.
        #[arg(long)]
        expected_fingerprint: String,
    },
    List,
    Revoke {
        #[arg(long)]
        peer_device: String,
        #[arg(long)]
        expected_fingerprint: String,
    },
}
#[derive(Clone, Copy, ValueEnum)]
enum Slot {
    Primary,
    Fallback,
}
impl From<Slot> for EndpointSlot {
    fn from(s: Slot) -> Self {
        match s {
            Slot::Primary => Self::Primary,
            Slot::Fallback => Self::Fallback,
        }
    }
}
#[derive(Subcommand)]
enum EndpointAction {
    Set {
        #[arg(long)]
        peer_device: String,
        #[arg(long, value_enum)]
        slot: Slot,
        #[arg(long)]
        url: String,
        #[arg(long)]
        expected_fingerprint: String,
    },
    List {
        #[arg(long)]
        peer_device: String,
    },
    Clear {
        #[arg(long)]
        peer_device: String,
        #[arg(long, value_enum)]
        slot: Slot,
        #[arg(long)]
        expected_fingerprint: String,
    },
}
fn decode_key(value: &str) -> Result<Zeroizing<[u8; 32]>> {
    ensure!(
        value.len() == 64 && value.is_ascii(),
        "key must be exactly 64 hexadecimal characters (value omitted)"
    );
    let mut out = Zeroizing::new([0; 32]);
    for (i, byte) in out.iter_mut().enumerate() {
        *byte = u8::from_str_radix(&value[i * 2..i * 2 + 2], 16)
            .map_err(|_| anyhow::anyhow!("invalid key hex (value omitted)"))?;
    }
    Ok(out)
}
fn public_hex(bytes: [u8; 32]) -> String {
    use std::fmt::Write;
    let mut out = String::with_capacity(64);
    for b in bytes {
        write!(&mut out, "{b:02x}").expect("string format");
    }
    out
}
pub fn run(args: FleetArgs) -> Result<Value> {
    let protection = if let Some(name) = &args.wrapping_key_env {
        let key = Zeroizing::new(std::env::var(name).map_err(|_| {
            anyhow::anyhow!("external wrapping-key environment missing/invalid (value omitted)")
        })?);
        Protection::supplied_key(decode_key(&key)?)?
    } else {
        Protection::windows_current_user()?
    };
    execute(args, protection)
}
fn execute(args: FleetArgs, protection: Protection) -> Result<Value> {
    let store = if matches!(&args.action, FleetAction::Init) {
        IdentityStore::create(&args.store, protection, args.fleet_id, &args.device_id)?
    } else {
        IdentityStore::open(&args.store, protection, args.fleet_id, &args.device_id)?
    };
    let value = match args.action {
        FleetAction::Init | FleetAction::Identity => {
            let key = if matches!(&args.action, FleetAction::Init) {
                store.create_identity()?
            } else {
                store.load_identity()?
            };
            json!({"device":args.device_id,"fleetId":args.fleet_id,"publicKeyHex":public_hex(key.public()),"fingerprint":store.local_fingerprint()?.hex(),"deviceDigest":crate::fleet::protocol::device_digest(&args.device_id)?.iter().map(|b|format!("{b:02x}")).collect::<String>()})
        }
        FleetAction::Peer { action } => match action {
            PeerAction::Enroll {
                peer_device,
                label,
                public_key,
                expected_fingerprint,
            } => {
                let expected = Fingerprint::parse_hex(&expected_fingerprint)?;
                let approval = PeerApproval::verify(
                    args.fleet_id,
                    &peer_device,
                    *decode_key(&public_key)?,
                    &expected,
                )?;
                let now = u64::try_from(
                    std::time::SystemTime::now()
                        .duration_since(std::time::UNIX_EPOCH)
                        .context("local enrollment timestamp before UNIX epoch")?
                        .as_millis(),
                )?;
                let kind = store.enroll_peer(approval, &label, now)?;
                json!({"device":peer_device,"label":label,"admission":match kind{PeerAdmission::Created=>"created",PeerAdmission::Existing=>"existing"}})
            }
            PeerAction::List => {
                let rows=store.peers()?.iter().map(|p|Ok(json!({"device":p.device(),"label":p.label(),"fingerprint":p.fingerprint(args.fleet_id)?.hex(),"addedMs":p.added_ms()}))).collect::<Result<Vec<_>>>()?;
                json!({"peers":rows})
            }
            PeerAction::Revoke {
                peer_device,
                expected_fingerprint,
            } => {
                ensure!(
                    store.endpoints_for(&peer_device)?.is_empty(),
                    "clear approved endpoint slots before revoking this peer"
                );
                let removed = store.revoke_peer(
                    &peer_device,
                    &Fingerprint::parse_hex(&expected_fingerprint)?,
                )?;
                json!({"device":peer_device,"revoked":removed})
            }
        },
        FleetAction::Endpoint { action } => match action {
            EndpointAction::Set {
                peer_device,
                slot,
                url,
                expected_fingerprint,
            } => {
                let kind = store.set_peer_endpoint(
                    &peer_device,
                    slot.into(),
                    &url,
                    &Fingerprint::parse_hex(&expected_fingerprint)?,
                )?;
                json!({"device":peer_device,"slot":EndpointSlot::from(slot).as_str(),"admission":format!("{kind:?}")})
            }
            EndpointAction::List { peer_device } => {
                let rows = store
                    .endpoints_for(&peer_device)?
                    .iter()
                    .map(|e| json!({"slot":e.slot().as_str(),"url":e.url()}))
                    .collect::<Vec<_>>();
                json!({"device":peer_device,"endpoints":rows})
            }
            EndpointAction::Clear {
                peer_device,
                slot,
                expected_fingerprint,
            } => {
                let removed = store.clear_peer_endpoint(
                    &peer_device,
                    slot.into(),
                    &Fingerprint::parse_hex(&expected_fingerprint)?,
                )?;
                json!({"device":peer_device,"slot":EndpointSlot::from(slot).as_str(),"removed":removed})
            }
        },
    };
    Ok(json!({"localOnly":true,"mcpFleetToolsEnabled":false,"result":value}))
}
